"""Action Recommendations Widget for TicNet Results Presentation.

Presents prioritized, evidence-linked remediation actions in clear, beginner-friendly English:
- Section 1: Immediate Steps for Home Users (step-by-step guidance).
- Section 2: Technical Parameters for ISP / Technician Support (specific diagnostic figures to quote).
- Explicit Disclaimer: Strictly warns never to claim an unproven physical cable or ISP fault.

Strict Invariants:
- Uses ONLY recommendations generated by the existing RecommendationEngine / FindingRecommendation.
- Never fabricates synthetic remediation claims.
"""

from __future__ import annotations

from typing import List, Optional

from PySide6.QtCore import Qt
from PySide6.QtGui import QColor
from PySide6.QtWidgets import (
    QFrame,
    QHBoxLayout,
    QLabel,
    QVBoxLayout,
    QWidget,
)

from ticnet.desktop.theme import ThemeTokens
from ticnet.diagnosis.recommender import FindingRecommendation


class RecommendationsPanel(QFrame):
    """Recommendations panel partitioning action items for home users versus technicians."""

    def __init__(self, parent: Optional[QWidget] = None) -> None:
        super().__init__(parent)
        self.setStyleSheet(
            f"background-color: {ThemeTokens.BG_CARD}; "
            f"border: 1px solid {ThemeTokens.BORDER_DEFAULT}; "
            f"border-radius: {ThemeTokens.RADIUS_DEFAULT};"
        )
        self.main_layout = QVBoxLayout(self)
        self.main_layout.setContentsMargins(16, 14, 16, 14)
        self.main_layout.setSpacing(10)

        # Header
        header_widget = QWidget(self)
        h_layout = QHBoxLayout(header_widget)
        h_layout.setContentsMargins(0, 0, 0, 0)

        title_lbl = QLabel("Actionable Recommendations", header_widget)
        title_lbl.setStyleSheet(f"font-size: 14px; font-weight: 700; color: {ThemeTokens.TEXT_PRIMARY};")
        h_layout.addWidget(title_lbl)

        badge_lbl = QLabel("Deterministic Action Plan | Audience Split", header_widget)
        badge_lbl.setStyleSheet(
            f"font-size: 11px; font-weight: 600; color: {ThemeTokens.BRAND_PRIMARY}; "
            f"background-color: {ThemeTokens.BG_MUTED}; padding: 2px 8px; "
            f"border-radius: {ThemeTokens.RADIUS_PILL};"
        )
        h_layout.addWidget(badge_lbl)
        h_layout.addStretch()
        self.main_layout.addWidget(header_widget)

        # Subtitle
        sub_lbl = QLabel(
            "Concrete steps tailored for both home users and network technicians. Every recommendation is "
            "directly derived from confirmed findings without speculative root-cause claims.",
            self,
        )
        sub_lbl.setStyleSheet(f"color: {ThemeTokens.TEXT_MUTED}; font-size: 12px;")
        sub_lbl.setWordWrap(True)
        self.main_layout.addWidget(sub_lbl)

        # Content container
        self.actions_container = QWidget(self)
        self.actions_layout = QVBoxLayout(self.actions_container)
        self.actions_layout.setContentsMargins(0, 0, 0, 0)
        self.actions_layout.setSpacing(8)
        self.main_layout.addWidget(self.actions_container)

        # Legal / Safety Disclaimer
        self.disclaimer_card = QFrame(self)
        self.disclaimer_card.setStyleSheet(
            f"background-color: {ThemeTokens.BG_MUTED}; "
            f"border: 1px solid {ThemeTokens.BORDER_DEFAULT}; "
            f"border-radius: 6px;"
        )
        disc_layout = QVBoxLayout(self.disclaimer_card)
        disc_layout.setContentsMargins(12, 10, 12, 10)
        self.lbl_disclaimer = QLabel(
            "<b>Diagnostic Boundary Reminder:</b> TicNet provides observational measurements to isolate failure domains. "
            "Do not claim that a physical damaged cable or ISP backbone outage is conclusively proven without "
            "on-site loop diagnostics from your Internet Service Provider.",
            self.disclaimer_card,
        )
        self.lbl_disclaimer.setStyleSheet(f"font-size: 11px; color: {ThemeTokens.TEXT_MUTED}; line-height: 1.3;")
        self.lbl_disclaimer.setWordWrap(True)
        disc_layout.addWidget(self.lbl_disclaimer)
        self.main_layout.addWidget(self.disclaimer_card)

    def populate_recommendations(self, recommendations: List[FindingRecommendation]) -> None:
        """Render user and technician action items from recommendations."""
        # Clear existing action items
        while self.actions_layout.count() > 0:
            item = self.actions_layout.takeAt(0)
            if item is not None:
                w = item.widget()
                if w:
                    w.deleteLater()

        if not recommendations:
            lbl_empty = QLabel(
                "✓ No remedial actions required. Your network connection satisfies all baseline performance thresholds.",
                self.actions_container,
            )
            lbl_empty.setStyleSheet(f"color: {ThemeTokens.COLOR_SUCCESS}; font-size: 13px; font-weight: 600; padding: 10px 0;")
            self.actions_layout.addWidget(lbl_empty)
            return

        for rec in recommendations:
            rec_box = QFrame(self.actions_container)
            rec_box.setStyleSheet(
                f"background-color: {ThemeTokens.BG_MUTED}; "
                f"border: 1px solid {ThemeTokens.BORDER_DEFAULT}; "
                f"border-radius: {ThemeTokens.RADIUS_DEFAULT};"
            )
            r_layout = QVBoxLayout(rec_box)
            r_layout.setContentsMargins(12, 10, 12, 10)
            r_layout.setSpacing(6)

            # Finding Reference Header
            top_row = QWidget(rec_box)
            tr_layout = QHBoxLayout(top_row)
            tr_layout.setContentsMargins(0, 0, 0, 0)
            lbl_rule = QLabel(f"<b>For Finding: {rec.rule_id}</b> — {rec.summary}", top_row)
            lbl_rule.setStyleSheet(f"font-size: 12px; color: {ThemeTokens.BRAND_PRIMARY};")
            tr_layout.addWidget(lbl_rule)
            tr_layout.addStretch()
            r_layout.addWidget(top_row)

            # User Actions
            if rec.user_actions:
                lbl_u_head = QLabel("<b>Recommended Actions for Home Users:</b>", rec_box)
                lbl_u_head.setStyleSheet(f"font-size: 12px; color: {ThemeTokens.TEXT_PRIMARY};")
                r_layout.addWidget(lbl_u_head)

                for act in rec.user_actions:
                    act_widget = QWidget(rec_box)
                    act_layout = QVBoxLayout(act_widget)
                    act_layout.setContentsMargins(8, 2, 8, 4)
                    act_layout.setSpacing(2)

                    lbl_title = QLabel(f"<b>Step {act.step_order}: {act.title}</b>", act_widget)
                    lbl_title.setStyleSheet(f"font-size: 12px; color: {ThemeTokens.TEXT_PRIMARY};")
                    act_layout.addWidget(lbl_title)

                    lbl_desc = QLabel(act.description, act_widget)
                    lbl_desc.setStyleSheet(f"font-size: 11px; color: {ThemeTokens.TEXT_SECONDARY}; line-height: 1.3;")
                    lbl_desc.setWordWrap(True)
                    act_layout.addWidget(lbl_desc)

                    r_layout.addWidget(act_widget)

            # Technician Actions
            if rec.technician_actions:
                lbl_t_head = QLabel("<b>Technical Parameters for ISP Support / Technician:</b>", rec_box)
                lbl_t_head.setStyleSheet(f"font-size: 12px; color: {ThemeTokens.TEXT_PRIMARY}; margin-top: 6px;")
                r_layout.addWidget(lbl_t_head)

                for act in rec.technician_actions:
                    act_widget = QWidget(rec_box)
                    act_layout = QVBoxLayout(act_widget)
                    act_layout.setContentsMargins(8, 2, 8, 4)
                    act_layout.setSpacing(2)

                    lbl_title = QLabel(f"• <b>{act.title}</b>", act_widget)
                    lbl_title.setStyleSheet(f"font-size: 12px; color: {ThemeTokens.TEXT_PRIMARY};")
                    act_layout.addWidget(lbl_title)

                    lbl_desc = QLabel(f"{act.description} (<i>Rationale: {act.rationale}</i>)", act_widget)
                    lbl_desc.setStyleSheet(f"font-size: 11px; color: {ThemeTokens.TEXT_SECONDARY}; line-height: 1.3;")
                    lbl_desc.setWordWrap(True)
                    act_layout.addWidget(lbl_desc)

                    r_layout.addWidget(act_widget)

            self.actions_layout.addWidget(rec_box)
